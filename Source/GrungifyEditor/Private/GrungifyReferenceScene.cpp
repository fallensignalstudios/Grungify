const TCHAR* FGrungifyReferenceScene::MapPackageName()
{
	return TEXT("/Game/Grungify/Reference/L_GrungifyReference");
}

bool FGrungifyReferenceScene::Build(FString& OutMessage)
{
	auto Fail = [&OutMessage](const FString& Message)
	{
		OutMessage = TEXT("Grungify reference scene: ") + Message;
		UE_LOG(LogGrungify, Error, TEXT("%s"), *OutMessage);
		return false;
	};

	if (!GEditor)
	{
		return Fail(TEXT("needs the editor"));
	}
	if (GEditor->PlayWorld)
	{
		return Fail(TEXT("stop Play In Editor first"));
	}

	FScopedSlowTask Progress(6.f, LOCTEXT("Building", "Grungify: building the reference scene..."));
	Progress.MakeDialog();

	// ------------------------------------------------------------- Assets
	Progress.EnterProgressFrame(1.f, LOCTEXT("Assets", "Creating reference materials and the Nanite mesh..."));
	UMaterialInterface* Parent = Cast<UMaterialInterface>(FindAsset(ExampleMaterialPath));
	if (!Parent)
	{
		return Fail(TEXT("M_GrungifyExample is missing; run Tools > Grungify > Update Plugin Content first"));
	}
	{
		FLinearColor Color;
		float Scalar = 0.f;
		const bool bHasParameters = Parent->GetVectorParameterValue(FMaterialParameterInfo(TEXT("Base Color")), Color)
			&& Parent->GetScalarParameterValue(FMaterialParameterInfo(TEXT("Roughness")), Scalar)
			&& Parent->GetScalarParameterValue(FMaterialParameterInfo(TEXT("Metallic")), Scalar)
			&& Parent->GetScalarParameterValue(FMaterialParameterInfo(Grungify::SurfaceOverrideParameterName()), Scalar);
		if (!bHasParameters)
		{
			return Fail(TEXT("M_GrungifyExample lacks Base Color / Roughness / Metallic / Grungify Surface Override; rebuild plugin content"));
		}
	}

	UStaticMesh* Cube = LoadObject<UStaticMesh>(nullptr, CubePath);
	UStaticMesh* Cylinder = LoadObject<UStaticMesh>(nullptr, CylinderPath);
	UStaticMesh* Plane = LoadObject<UStaticMesh>(nullptr, PlanePath);
	if (!Cube || !Cylinder || !Plane)
	{
		return Fail(TEXT("engine basic shapes (/Engine/BasicShapes) are missing"));
	}

	TArray<UPackage*> Packages;
	FString Error;
	UMaterialInstanceConstant* Stone = MakeMaterial({ TEXT("MI_GrungifyRef_Stone"), FLinearColor(0.42f, 0.38f, 0.33f), 0.85f, 0.f }, Parent, Packages, Error);
	UMaterialInstanceConstant* Metal = Stone ? MakeMaterial({ TEXT("MI_GrungifyRef_Metal"), FLinearColor(0.10f, 0.12f, 0.14f), 0.45f, 0.2f }, Parent, Packages, Error) : nullptr;
	UMaterialInstanceConstant* Trim = Metal ? MakeMaterial({ TEXT("MI_GrungifyRef_Trim"), FLinearColor(0.78f, 0.72f, 0.58f), 0.6f, 0.f }, Parent, Packages, Error) : nullptr;
	UMaterialInstanceConstant* Floor = Trim ? MakeMaterial({ TEXT("MI_GrungifyRef_Floor"), FLinearColor(0.35f, 0.35f, 0.33f), 0.9f, 0.f }, Parent, Packages, Error) : nullptr;
	UStaticMesh* NaniteCube = Floor ? MakeNaniteCube(Cube, Packages, Error) : nullptr;
	if (!NaniteCube)
	{
		return Fail(Error);
	}
	if (!UEditorLoadingAndSavingUtils::SavePackages(Packages, /*bOnlyDirty*/ false))
	{
		return Fail(TEXT("could not save the reference materials or the Nanite mesh"));
	}

	// -------------------------------------------------------------- Level
	Progress.EnterProgressFrame(1.f, LOCTEXT("Level", "Opening the reference level..."));
	// The editor switches to the reference map, so the user's open level is offered for saving first (cancel aborts).
	if (!FEditorFileUtils::SaveDirtyPackages(/*bPromptUserToSave*/ true, /*bSaveMapPackages*/ true, /*bSaveContentPackages*/ false))
	{
		return Fail(TEXT("cancelled; the open level was left as it was"));
	}

	// Rebuilding reuses the existing package rather than saving a new world over it, which a loaded package would block.
	const FString MapPackage = MapPackageName();
	const bool bExistingMap = FPackageName::DoesPackageExist(MapPackage);
	UWorld* World = bExistingMap
		? UEditorLoadingAndSavingUtils::LoadMap(FPackageName::LongPackageNameToFilename(MapPackage, FPackageName::GetMapPackageExtension()))
		: UEditorLoadingAndSavingUtils::NewBlankMap(/*bSaveExistingMap*/ false);
	if (!World || !World->PersistentLevel)
	{
		return Fail(bExistingMap ? TEXT("could not open the existing reference map") : TEXT("could not create a new map"));
	}
	if (bExistingMap)
	{
		TArray<AActor*> OldActors;
		for (AActor* Actor : World->PersistentLevel->Actors)
		{
			if (Actor && !Actor->IsA<AWorldSettings>() && Actor != World->GetDefaultBrush())
			{
				OldActors.Add(Actor);
			}
		}
		for (AActor* Actor : OldActors)
		{
			World->EditorDestroyActor(Actor, /*bShouldModifyLevel*/ true);
		}
	}
	if (AWorldSettings* WorldSettings = World->GetWorldSettings())
	{
		// Static meshes stay Static (as the zone expects) without a lighting build or an "unbuilt lighting" overlay.
		WorldSettings->Modify();
		WorldSettings->bForceNoPrecomputedLighting = true;
	}

	SetupLighting(World);

	// ------------------------------------------------------------ Content
	// Roughly 10 m x 6 m. The back wall's front face is at Y = 230 and faces -Y, towards every camera.
	Progress.EnterProgressFrame(1.f, LOCTEXT("Content", "Placing the reference meshes..."));
	const UGrungifySettings* Settings = UGrungifySettings::Get();
	const FVector VentLocation(-250., 225., 230.);
	const FVector LampLocation(50., 205., 240.);

	const bool bPlaced =
		SpawnMesh(World, TEXT("Floor_Concrete"), Cube, Floor,
			FTransform(FRotator::ZeroRotator, FVector(0., 0., -10.), FVector(10., 6., 0.2)), { Settings->FloorTag })
		&& SpawnMesh(World, TEXT("Wall_Stone"), Cube, Stone,
			FTransform(FRotator::ZeroRotator, FVector(-150., 250., 150.), FVector(6., 0.4, 3.)), { Settings->StoneTag })
		// A single quad: 4 vertices over 9 m2, so Auto picks the texture output. Local Z faces -Y, local Y points up.
		&& SpawnMesh(World, TEXT("Wall_SparseQuad"), Plane, Stone,
			FTransform(FRotationMatrix::MakeFromZX(FVector(0., -1., 0.), FVector(1., 0., 0.)).Rotator(), FVector(300., 250., 150.), FVector(3., 3., 1.)),
			{ Settings->StoneTag })
		// Pitch 90 lays the cylinder's Z axis along X; 6 cm thick, 5.5 m long, at hand height.
		&& SpawnMesh(World, TEXT("Rail_Metal"), Cylinder, Metal,
			FTransform(FRotator(90.f, 0.f, 0.f), FVector(-150., 215., 100.), FVector(0.06, 0.06, 5.5)), { Settings->MetalTag, Settings->RailTag })
		&& SpawnMesh(World, TEXT("Trim_Cornice"), Cube, Trim,
			FTransform(FRotator::ZeroRotator, FVector(-150., 223., 290.), FVector(6.1, 0.15, 0.12)), { Settings->TrimTag })
		&& SpawnMesh(World, TEXT("Vent_Wall"), Cube, Metal,
			FTransform(FRotator::ZeroRotator, VentLocation, FVector(0.4, 0.1, 0.25)), { Settings->VentTag, Settings->MetalTag })
		&& SpawnMesh(World, TEXT("NaniteCoffer_Stone"), NaniteCube, Stone,
			FTransform(FRotator::ZeroRotator, FVector(50., -180., 30.), FVector(1.2, 0.8, 0.6)), { Settings->StoneTag });
	if (!bPlaced)
	{
		return Fail(TEXT("could not spawn the reference meshes"));
	}

	if (APointLight* Lamp = SpawnLight<APointLight>(World, TEXT("Lamp"), LampLocation, FRotator::ZeroRotator))
	{
		if (UPointLightComponent* Component = Cast<UPointLightComponent>(Lamp->GetLightComponent()))
		{
			Component->SetMobility(EComponentMobility::Movable);
			Component->SetIntensityUnits(ELightUnits::Candelas);
			Component->SetIntensity(6.f);
			Component->SetAttenuationRadius(400.f);
			Component->SetLightColor(FLinearColor(1.f, 0.8f, 0.6f));
		}
	}

	// --------------------------------------------------------------- Zone
	Progress.EnterProgressFrame(1.f, LOCTEXT("Apply", "Applying the weathering zone..."));
	UClass* ZoneClass = AGrungifyWeatheringZone::StaticClass();
	if (const UBlueprint* Blueprint = Cast<UBlueprint>(FindAsset(ZoneBlueprintPath)))
	{
		if (Blueprint->GeneratedClass && Blueprint->GeneratedClass->IsChildOf(ZoneClass))
		{
			ZoneClass = Blueprint->GeneratedClass;
		}
	}
	AGrungifyWeatheringZone* Zone = World->SpawnActor<AGrungifyWeatheringZone>(ZoneClass, FVector(0., 0., 200.), FRotator::ZeroRotator, SpawnParams());
	if (!Zone || !Zone->GetZoneComponent())
	{
		return Fail(TEXT("could not spawn the weathering zone"));
	}
	Zone->bLivePreview = false;
	Zone->SetActorLabel(TEXT("WeatheringZone_Reference"));
	Zone->Seed = ReferenceSeed;
	Zone->MaskOutput = EGrungifyMaskOutput::Auto;
	Zone->Extended.MoistureIntensity = 0.6f;
	Zone->Extended.SootIntensity = 0.8f;
	Zone->GetZoneComponent()->SetBoxExtent(FVector(520., 320., 220.));

	FGrungifyLeak Leak;
	// Just under the vent's front face, so the streak runs down the wall rather than inside the vent box.
	Leak.Location = Zone->GetActorTransform().InverseTransformPosition(VentLocation + FVector(0., -6., -15.));
	Leak.RadiusCm = 12.f;
	Leak.Strength = 1.f;
	Zone->Leaks.Add(Leak);

	Zone->Apply();
	const int32 Weathered = Zone->GetAppliedCount();
	if (Weathered == 0)
	{
		return Fail(FString::Printf(TEXT("Apply weathered no meshes (%s)"), *Zone->Status));
	}

	// ---------------------------------------------------- Screenshot tests
	Progress.EnterProgressFrame(1.f, LOCTEXT("Screenshots", "Placing screenshot tests..."));
	const bool bScreenshots =
		PlaceScreenshotTest(World, TEXT("Screenshot_WallRailRunoff"), FVector(-200., -150., 160.), FVector(-200., 250., 150.))
		&& PlaceScreenshotTest(World, TEXT("Screenshot_SparseQuadWall"), FVector(300., -50., 150.), FVector(300., 250., 150.))
		&& PlaceScreenshotTest(World, TEXT("Screenshot_NaniteCoffer"), FVector(210., -340., 130.), FVector(50., -180., 30.))
		&& PlaceScreenshotTest(World, TEXT("Screenshot_Overview"), FVector(0., -650., 450.), FVector(-50., 150., 100.));
	if (!bScreenshots)
	{
		return Fail(TEXT("could not place or configure the screenshot functional tests"));
	}

	// --------------------------------------------------------------- Save
	Progress.EnterProgressFrame(1.f, LOCTEXT("Saving", "Saving the reference map..."));
	const bool bSaved = bExistingMap
		? FEditorFileUtils::SaveLevel(World->PersistentLevel)
		: UEditorLoadingAndSavingUtils::SaveMap(World, MapPackage);
	if (!bSaved)
	{
		return Fail(FString::Printf(TEXT("could not save %s"), *MapPackage));
	}
	// Undo would otherwise step back through the half-built scene after it was saved.
	GEditor->ResetTransaction(LOCTEXT("ResetTransaction", "Grungify reference scene built"));

	OutMessage = FString::Printf(TEXT("Grungify reference scene: built %s (now open), weathered %d mesh(es) with seed %d, placed 4 screenshot tests."),
		*MapPackage, Weathered, ReferenceSeed);
	UE_LOG(LogGrungify, Log, TEXT("%s"), *OutMessage);
	return true;
}

