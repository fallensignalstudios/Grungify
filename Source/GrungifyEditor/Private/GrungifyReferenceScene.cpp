	// Project content only: plugin content is regenerated by Update / Rebuild Plugin Content.
	const TCHAR* ReferenceFolder = TEXT("/Game/Grungify/Reference");
	const TCHAR* ExampleMaterialPath = TEXT("/Grungify/Materials/M_GrungifyExample");
	const TCHAR* ZoneBlueprintPath = TEXT("/Grungify/BP_WeatheringZone");
	const TCHAR* CubePath = TEXT("/Engine/BasicShapes/Cube.Cube");
	const TCHAR* CylinderPath = TEXT("/Engine/BasicShapes/Cylinder.Cylinder");
	const TCHAR* PlanePath = TEXT("/Engine/BasicShapes/Plane.Plane");

	constexpr EObjectFlags AssetFlags = RF_Public | RF_Standalone | RF_Transactional;
	constexpr int32 ReferenceSeed = 1337;

	FString ObjectPathFor(const FString& PackagePath)
	{
		return FString::Printf(TEXT("%s.%s"), *PackagePath, *FPackageName::GetShortName(PackagePath));
	}

	/** The asset at PackagePath, loading it if needed; null if there is none. */
	UObject* FindAsset(const FString& PackagePath)
	{
		const FString ObjectPath = ObjectPathFor(PackagePath);
		if (UObject* Loaded = FindObject<UObject>(nullptr, *ObjectPath))
		{
			return Loaded;
		}
		if (!FPackageName::DoesPackageExist(PackagePath))
		{
			return nullptr;
		}
		return LoadObject<UObject>(nullptr, *ObjectPath, nullptr, LOAD_NoWarn | LOAD_Quiet);
	}

	struct FMaterialLook
	{
		const TCHAR* Name;
		FLinearColor BaseColor;
		float Roughness;
		float Metallic;
	};

	UMaterialInstanceConstant* MakeMaterial(const FMaterialLook& Look, UMaterialInterface* Parent, TArray<UPackage*>& Packages, FString& OutError)
	{
		const FString PackagePath = FString::Printf(TEXT("%s/%s"), ReferenceFolder, Look.Name);
		UObject* Existing = FindAsset(PackagePath);
		UMaterialInstanceConstant* Instance = Cast<UMaterialInstanceConstant>(Existing);
		if (Existing && !Instance)
		{
			OutError = FString::Printf(TEXT("%s exists but is not a material instance; delete or rename it and build again"), *PackagePath);
			return nullptr;
		}
		if (!Instance)
		{
			Instance = NewObject<UMaterialInstanceConstant>(CreatePackage(*PackagePath), Look.Name, AssetFlags);
			FAssetRegistryModule::AssetCreated(Instance);
		}

		// Overwrite rather than merge, so hand edits to the reference materials can't drift the ground truth.
		Instance->Modify();
		Instance->ClearParameterValuesEditorOnly();
		Instance->SetParentEditorOnly(Parent);
		Instance->SetVectorParameterValueEditorOnly(FMaterialParameterInfo(TEXT("Base Color")), Look.BaseColor);
		Instance->SetScalarParameterValueEditorOnly(FMaterialParameterInfo(TEXT("Roughness")), Look.Roughness);
		Instance->SetScalarParameterValueEditorOnly(FMaterialParameterInfo(TEXT("Metallic")), Look.Metallic);
		// The actor tags classify the surfaces; -1 keeps that classification.
		Instance->SetScalarParameterValueEditorOnly(FMaterialParameterInfo(Grungify::SurfaceOverrideParameterName()), -1.f);
		Instance->PostEditChange();
		Instance->MarkPackageDirty();
		Packages.AddUnique(Instance->GetPackage());
		return Instance;
	}

	UStaticMesh* MakeNaniteCube(UStaticMesh* Cube, TArray<UPackage*>& Packages, FString& OutError)
	{
		const FString PackagePath = FString::Printf(TEXT("%s/SM_GrungifyNaniteCube"), ReferenceFolder);
		UObject* Existing = FindAsset(PackagePath);
		UStaticMesh* Mesh = Cast<UStaticMesh>(Existing);
		if (Existing && !Mesh)
		{
			OutError = FString::Printf(TEXT("%s exists but is not a static mesh; delete or rename it and build again"), *PackagePath);
			return nullptr;
		}
		if (!Mesh)
		{
			Mesh = DuplicateObject<UStaticMesh>(Cube, CreatePackage(*PackagePath), *FPackageName::GetShortName(PackagePath));
			Mesh->SetFlags(AssetFlags);
			FAssetRegistryModule::AssetCreated(Mesh);
		}
		Mesh->Modify();
		Mesh->GetNaniteSettings().bEnabled = true;
		// PostEditChange rebuilds the render data, including the Nanite resources and the fallback mesh the masks bake from.
		Mesh->PostEditChange();
		Mesh->MarkPackageDirty();
		Packages.AddUnique(Mesh->GetPackage());
		return Mesh;
	}

	FActorSpawnParameters SpawnParams()
	{
		FActorSpawnParameters Params;
		Params.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AlwaysSpawn;
		return Params;
	}

	AStaticMeshActor* SpawnMesh(UWorld* World, const TCHAR* Label, UStaticMesh* Mesh, UMaterialInterface* Material,
		const FTransform& Transform, std::initializer_list<FName> Tags)
	{
		AStaticMeshActor* Actor = World->SpawnActor<AStaticMeshActor>(AStaticMeshActor::StaticClass(), Transform, SpawnParams());
		if (!Actor)
		{
			return nullptr;
		}
		UStaticMeshComponent* Component = Actor->GetStaticMeshComponent();
		Component->SetMobility(EComponentMobility::Static);
		Component->SetStaticMesh(Mesh);
		Component->SetMaterial(0, Material);
		Actor->SetActorLabel(Label);
		Actor->Tags.Append(Tags);
		return Actor;
	}

	template <typename TLight>
	TLight* SpawnLight(UWorld* World, const TCHAR* Label, const FVector& Location, const FRotator& Rotation)
	{
		TLight* Light = World->SpawnActor<TLight>(Location, Rotation, SpawnParams());
		if (Light)
		{
			Light->SetActorLabel(Label);
		}
		return Light;
	}

	void SetupLighting(UWorld* World)
	{
		// Movable lights render identically without a lighting build, so captures don't depend on lightmaps.
		if (ADirectionalLight* Sun = SpawnLight<ADirectionalLight>(World, TEXT("Sun"), FVector(0., 0., 800.), FRotator(-40.f, 60.f, 0.f)))
		{
			if (UDirectionalLightComponent* Component = Cast<UDirectionalLightComponent>(Sun->GetLightComponent()))
			{
				Component->SetMobility(EComponentMobility::Movable);
				Component->SetIntensity(8.f);
				Component->SetLightColor(FLinearColor(1.f, 0.96f, 0.9f));
				Component->SetAtmosphereSunLight(true);
			}
		}
		if (ASkyLight* Sky = SpawnLight<ASkyLight>(World, TEXT("SkyLight"), FVector(0., 0., 700.), FRotator::ZeroRotator))
		{
			if (USkyLightComponent* Component = Sky->GetLightComponent())
			{
				Component->SetMobility(EComponentMobility::Movable);
				Component->bRealTimeCapture = true;
				Component->SetIntensity(1.f);
				Component->MarkRenderStateDirty();
			}
		}
		if (ASkyAtmosphere* Atmosphere = World->SpawnActor<ASkyAtmosphere>(FVector::ZeroVector, FRotator::ZeroRotator, SpawnParams()))
		{
			Atmosphere->SetActorLabel(TEXT("SkyAtmosphere"));
		}
		// No height fog: one less temporally accumulated effect in the captures.

		if (APostProcessVolume* Volume = World->SpawnActor<APostProcessVolume>(FVector::ZeroVector, FRotator::ZeroRotator, SpawnParams()))
		{
			Volume->SetActorLabel(TEXT("PostProcess_FixedExposure"));
			Volume->bUnbound = true;
			FPostProcessSettings& Settings = Volume->Settings;
			Settings.bOverride_AutoExposureMethod = true;
			Settings.AutoExposureMethod = EAutoExposureMethod::AEM_Manual;
			Settings.bOverride_AutoExposureApplyPhysicalCameraExposure = true;
			Settings.AutoExposureApplyPhysicalCameraExposure = false;
			Settings.bOverride_AutoExposureBias = true;
			Settings.AutoExposureBias = 0.f;
			Settings.bOverride_MotionBlurAmount = true;
			Settings.MotionBlurAmount = 0.f;
			Settings.bOverride_VignetteIntensity = true;
			Settings.VignetteIntensity = 0.f;
			Settings.bOverride_BloomIntensity = true;
			Settings.BloomIntensity = 0.f;
		}
	}

	bool PlaceScreenshotTest(UWorld* World, const TCHAR* Label, const FVector& Location, const FVector& Target)
	{
		const FRotator Rotation = (Target - Location).Rotation();
		AScreenshotFunctionalTest* Test = World->SpawnActor<AScreenshotFunctionalTest>(Location, Rotation, SpawnParams());
		if (!Test)
		{
			return false;
		}
		// The functional test name is the actor label.
		Test->SetActorLabel(Label);

		if (UCameraComponent* Camera = Test->FindComponentByClass<UCameraComponent>())
		{
			Camera->SetWorldLocationAndRotation(Location, Rotation);
			Camera->SetFieldOfView(70.f);
			Camera->SetAspectRatio(1280.f / 720.f);
			Camera->SetConstraintAspectRatio(true);
		}

		// ScreenshotOptions is protected on AScreenshotFunctionalTestBase, so set it through reflection.
		const FStructProperty* Property = FindFProperty<FStructProperty>(AScreenshotFunctionalTest::StaticClass(), TEXT("ScreenshotOptions"));
		if (!Property || Property->Struct != FAutomationScreenshotOptions::StaticStruct())
		{
			return false;
		}
		FAutomationScreenshotOptions& Options = *Property->ContainerPtrToValuePtr<FAutomationScreenshotOptions>(Test);
		Options = FAutomationScreenshotOptions(EComparisonTolerance::Low);
		Options.Resolution = FVector2D(1280., 720.);
		// Lets the real-time sky capture and texture streaming settle before the capture.
		Options.Delay = 2.f;
		Options.bDisableNoisyRenderingFeatures = true;
		Options.bDisableTonemapping = false;
		return true;
	}
